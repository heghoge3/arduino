import java.util.Locale

/** Редкость — сложность условия, а не выдуманный процент игроков. */
enum class Rarity(val title: String) {
    COMMON("Обычное"), UNCOMMON("Необычное"), RARE("Редкое"), EPIC("Эпическое"), LEGENDARY("Легендарное")
}
enum class BadgeGroup(val title: String) {
    ROUTE("Маршруты"), STEPS("Шаги"), JOURNAL("Хроника"), TIME("Время"), CALENDAR("Сезоны"),
    LIGHT("Свет и ночь"), GEO("География"), WEATHER("Датчики"), MARKS("Метки"), SIGNAL("Связь")
}
data class Achievement(
    val id: String, val title: String, val condition: String, val group: BadgeGroup,
    val rarity: Rarity, val metric: String, val target: Double, val unit: String = "", val secret: Boolean = false,
)
data class AchievementProgress(val badge: Achievement, val value: Double, val unlockedMs: Long? = null, val new: Boolean = false) {
    val fraction: Float get() = (value / badge.target).coerceIn(0.0, 1.0).toFloat()
    val unlocked get() = unlockedMs != null
    val counter: String get() = "${number(value.coerceIn(0.0, badge.target))} / ${number(badge.target)}${if (badge.unit.isEmpty()) "" else " ${badge.unit}"}"
    private fun number(n: Double): String = if (n % 1.0 < .00001) String.format(Locale("ru"), "%,.0f", n)
        else String.format(Locale("ru"), if(kotlin.math.abs(badge.target*10-kotlin.math.round(badge.target*10))>.001) "%.2f" else "%.1f", n)
}

