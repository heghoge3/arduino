// Время: часы DS3231 с батарейкой + доверие к источнику (ТЗ, раздел 5).
// Порядок доверия: телефон → DS3231 → GPS без подмены.
#pragma once
#include <stdint.h>

namespace clockx {

enum Source : uint8_t { SRC_NONE = 0, SRC_RTC = 1, SRC_PHONE = 2, SRC_GPS = 3 };

// Запустить DS3231: проверить I2C/OSF и сохранённое доверие. true — модуль отвечает.
// cold — включение, а не пробуждение: при пробуждении без ответа DS3231 время берётся из внутренних часов
bool begin(bool cold);

// Текущее время, Unix-с UTC (внутренние часы ESP32, их ставят DS3231, телефон или GPS)
uint32_t now();
// Время работы с включения, включая фактически прошедший сон; перевод часов длительность не меняет.
uint32_t uptimeS();

// Время проверено: часы не стояли и их ставили с телефона или GPS
bool trusted();
Source source();
bool rtcPresent();

// Поставить время (и записать в DS3231)
void setFromPhone(uint32_t utc);
// Время GPS: ставим только если часы не проверены, и только без подозрения на подмену
int32_t offerGps(uint32_t utc, bool spoofSuspected);  // на сколько с переставили часы (0 — не брали)

// Перечитать проверенный DS3231 (раз в 10 мин); вернуть сдвиг для таймеров записи.
// Расхождение более 30 с не применяем молча к работающим системным часам.
int32_t resync();
int32_t rejectedResync();  // отклонённый сдвиг последней сверки, иначе 0

}  // namespace clockx
